#!/usr/bin/env python3
"""Generates odin/game/assets_data.odin from the original game's content (stdlib only).

Sources (src/BagelQuest/Content): hue.json (16 colours), Fonts/CyFont8x8.json (the UI font, ASCII 32..127, 8 by 8 cells)
and Fonts/BagelQuest.json (the game art: 256 glyphs of 16 by 16 pixels, indexed by character code).
Bit x of a row is the pixel in column x (bit 0 is the leftmost)."""
import os
from common import ROOT as root, HUE_NAMES, load
hues = load("hue.json")
assert sorted(int(k) for k in hues) == list(range(16))

def font(name, first, count, width, height):
    d = load(name)
    assert d["Height"] == height, name
    glyphs = d["Glyphs"]
    rows = []
    for code in range(first, first + count):
        g = glyphs[chr(code)]
        assert g["Width"] == width, (name, code)
        r = [0] * height
        for y, cols in g["Lines"].items():
            for x in cols:
                assert 0 <= int(y) < height and 0 <= x < width, (name, code, y, x)
                r[int(y)] |= 1 << x
        rows.append(r)
    assert len(glyphs) == count, (name, len(glyphs))
    return rows

ui = font("Fonts/CyFont8x8.json", 32, 96, 8, 8)
tiles = font("Fonts/BagelQuest.json", 0, 256, 16, 16)

o = ["package game", "",
     "// GENERATED by tools/gen/gen_assets.py from src/BagelQuest/Content (hue.json, CyFont8x8.json, BagelQuest.json). Do not edit.", "",
     "// The 16 hues of the original (BoilerplateHue), as 0xAABBGGRR so the bytes in memory are R, G, B, A.",
     "Hue :: enum u8 { " + ", ".join(HUE_NAMES) + " }", "", "PALETTE := [Hue]u32{"]
for i, n in enumerate(HUE_NAMES):
    c = hues[str(i)]
    assert c["A"] == 255
    o.append(f"\t.{n} = 0xFF{c['B']:02X}{c['G']:02X}{c['R']:02X},")
o += ["}", "",
      "// The UI font: ASCII 32 to 127 (index = code - 32), every glyph 8 pixels wide and 8 rows high. One byte per row.",
      "UI_FONT_FIRST :: 32", "UI_FONT_COUNT :: 96", "UI_FONT_CELL :: 8", "UI_FONT_ROWS := [UI_FONT_COUNT][UI_FONT_CELL]u8{"]
for i, r in enumerate(ui):
    o.append("\t{" + ", ".join(f"0x{b:02X}" for b in r) + "}, // " + repr(chr(32 + i)))
o += ["}", "",
      "// The game art: 256 glyphs of 16 by 16 pixels, indexed by the original's character code. One u16 per row.",
      "TILE_COUNT :: 256", "TILE_SIZE :: 16", "TILE_ROWS := [TILE_COUNT][TILE_SIZE]u16{"]
for i, r in enumerate(tiles):
    o.append("\t{" + ", ".join(f"0x{b:04X}" for b in r) + f"}}, // {i}")
o.append("}")
with open(os.path.join(root, "odin", "game", "assets_data.odin"), "w") as f:
    f.write("\n".join(o) + "\n")
print("wrote odin/game/assets_data.odin")
